export function renderSvg(name: IconName, size = 14, className = 'app-icon'): string {
  const content = ICONS[name] || ICONS.file;
  return `<svg class="${className}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${content}</svg>`;
}

export function createSvg(name: IconName, size = 14, className = 'app-icon'): SVGElement {
  const wrapper = document.createElement('div');
  wrapper.innerHTML = renderSvg(name, size, className);
  return wrapper.firstElementChild as SVGElement;
}

export function fileTypeIcon(fileName: string, isDirectory: boolean): IconName {
  if (isDirectory) return 'folder';
  const ext = fileName.toLowerCase().split('.').pop() || '';
  switch (ext) {
    case 'tex': return 'fileTex';
    case 'bib': return 'fileBib';
    case 'sty':
    case 'cls':
    case 'bst':
    case 'def':
    case 'cfg':
      return 'fileGear';
    case 'png':
    case 'jpg':
    case 'jpeg':
    case 'pdf':
    case 'eps':
    case 'svg':
      return 'fileImage';
    case 'txt':
    case 'md':
    case 'json':
    case 'csv':
      return 'fileText';
    default:
      return 'file';
  }
}
